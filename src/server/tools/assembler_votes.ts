/**
 * Assembler: turn votes from the generator page's rating tab into suggested value changes.
 *
 *   npx tsx src/server/tools/assembler_votes.ts votes.json [more.json ...] [--markdown out.md]
 *
 * Each file is a download from the page ({version: 1, votes: [...], valueVotes: [...]}). Files
 * from several people can be passed together. See src/server/assembler/AssemblerVoteFit.ts.
 */
import * as fs from 'fs';
import {AssemblerValueVote, AssemblerVote, AssemblerVoteFile, isVerdict} from '../../common/assembler/AssemblerVotes';
import {EFFECT_CATEGORY_INFO, isEffectCategory} from '../../common/assembler/EffectCategory';
import {Calibration, calibrate, fitVotes, summarizeValueVotes} from '../assembler/AssemblerVoteFit';

type Votes = {cards: Array<AssemblerVote>, values: Array<AssemblerValueVote>};

function read(path: string): Votes {
  const file = JSON.parse(fs.readFileSync(path, 'utf8')) as AssemblerVoteFile | Array<AssemblerVote>;
  const cards = Array.isArray(file) ? file : file.votes ?? [];
  const values = Array.isArray(file) ? [] : file.valueVotes ?? [];
  return {
    cards: cards.filter((v) => isVerdict(v.verdict) && v.assembled?.breakdown !== undefined),
    values: values.filter((v) => isVerdict(v.verdict) && typeof v.shown === 'number'),
  };
}

/** A vote that's in two files (downloaded twice without clearing) counts once. */
function unique<T extends {at: number}>(votes: Array<T>, id: (v: T) => string): Array<T> {
  return [...new Map(votes.map((v) => [`${id(v)}|${v.at}`, v])).values()];
}

function label(group: string): string {
  if (isEffectCategory(group)) {
    return EFFECT_CATEGORY_INFO[group].label;
  }
  return group === 'tags' ? 'Tags' : group === 'payment' ? 'Steel/titanium payment' : 'Requirements';
}

function fmt(n: number, digits = 1): string {
  return n.toFixed(digits);
}

function signed(n: number, digits = 1): string {
  return `${n >= 0 ? '+' : ''}${fmt(n, digits)}`;
}

function calibrationLines(c: Calibration): Array<string> {
  const lines = ['| Shown price | Votes | Average verdict |', '|---|---:|---:|'];
  for (const [name, row] of [['Moved down (cheaper than real)', c.down], ['Real', c.none], ['Moved up (pricier than real)', c.up]] as const) {
    lines.push(`| ${name} | ${row.count} | ${row.count > 0 ? signed(row.lean, 2) : '–'} |`);
  }
  const ok = c.down.count >= 5 && c.up.count >= 5;
  if (ok) {
    const gap = c.down.lean - c.up.lean;
    lines.push('', gap >= 0.75 ?
      `The votes notice wrong prices (moved down vs up differ by ${fmt(gap, 2)} steps): they can be trusted.` :
      `The votes barely notice wrong prices (moved down vs up differ by only ${fmt(gap, 2)} steps): treat them with care.`);
  } else {
    lines.push('', 'Too few moved prices yet to judge the votes (5 each way needed).');
  }
  return lines;
}

function report(paths: Array<string>): string {
  const all = paths.map(read);
  const cards = unique(all.flatMap((v) => v.cards), (v) => v.card);
  const values = unique(all.flatMap((v) => v.values), (v) => v.key);
  const lines: Array<string> = [];
  lines.push('# Assembler vote fit', '');
  lines.push(`${values.length} value votes and ${cards.length} card votes from ${paths.length} file(s). Generated by \`src/server/tools/assembler_votes.ts\`.`, '');
  lines.push('Average verdict: +2 worth much more / way too cheap, 0 about right, −2 worth much less / way too expensive.', '');

  if (values.length > 0) {
    lines.push('## Table values', '');
    lines.push('Suggested: the average of what each vote says the number should be (15% of the shown number per step).', '');
    lines.push('| Value | Votes | Average verdict | Table | Suggested | Change |', '|---|---:|---:|---:|---:|---:|');
    for (const r of summarizeValueVotes(values)) {
      const change = r.suggested - r.real;
      const mark = r.votes >= 5 && Math.abs(change) >= 0.1 * Math.abs(r.real) ? '**' : '';
      lines.push(`| ${r.label} | ${r.votes} | ${signed(r.lean, 2)} | ${fmt(r.real)} | ${mark}${fmt(r.suggested)}${mark} | ${signed(change)} |`);
    }
    lines.push('', '### Check on the value votes', '');
    lines.push(...calibrationLines(calibrate(values.map((v) => ({shift: v.shown - v.real, verdict: v.verdict})))), '');
  }

  if (cards.length > 0) {
    const fit = fitVotes(cards);
    lines.push('## Cards', '');
    lines.push(`Average distance between a card's shown price and what the votes say it's worth: ${fmt(fit.errorBefore)} M€ now, ${fmt(fit.errorAfter)} M€ with the factors below.`, '');
    lines.push(`Every card: ${signed(fit.offset)} M€ (positive: cards feel too cheap overall).`, '');
    lines.push('Factor: scale the values of that kind of effect by this much. 1.00 = priced right. Few votes = the factor stays near 1 by design.', '');
    lines.push('| Kind of effect | Votes | Average verdict | M€ on a card | Factor | Change on a card |', '|---|---:|---:|---:|---:|---:|');
    for (const g of fit.groups) {
      const mark = Math.abs(g.factor - 1) >= 0.1 && g.votes >= 10 ? '**' : '';
      lines.push(`| ${label(g.group)} | ${g.votes} | ${signed(g.lean, 2)} | ${fmt(g.value)} | ${mark}${fmt(g.factor, 2)}${mark} | ${signed((g.factor - 1) * g.value)} |`);
    }
    const spread = cards.filter((v) => v.shift !== undefined);
    if (spread.length > 0) {
      lines.push('', '### Check on the card votes', '');
      lines.push(...calibrationLines(calibrate(spread.map((v) => ({shift: v.shift ?? 0, verdict: v.verdict})))));
    }
  }
  return lines.join('\n') + '\n';
}

function main() {
  const args = process.argv.slice(2);
  const m = args.indexOf('--markdown');
  const out = m >= 0 ? args[m + 1] : undefined;
  const files = args.filter((a, i) => a !== '--markdown' && (m < 0 || i !== m + 1));
  if (files.length === 0) {
    console.error('Usage: npx tsx src/server/tools/assembler_votes.ts votes.json [more.json ...] [--markdown out.md]');
    process.exit(1);
  }
  const text = report(files);
  if (out !== undefined) {
    fs.writeFileSync(out, text);
    console.log(`Wrote ${out}`);
  }
  console.log(text);
}

if (require.main === module) {
  main();
}

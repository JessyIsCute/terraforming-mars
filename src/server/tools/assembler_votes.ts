/**
 * Assembler: turn votes from the generator page's "Rate cards" tab into suggested value changes.
 *
 *   npx tsx src/server/tools/assembler_votes.ts votes.json [more.json ...] [--markdown out.md]
 *
 * Each file is a download from the page ({version: 1, votes: [...]}). Files from several people
 * can be passed together. See src/server/assembler/AssemblerVoteFit.ts for how the fit works.
 */
import * as fs from 'fs';
import {AssemblerVote, AssemblerVoteFile, isVerdict} from '../../common/assembler/AssemblerVotes';
import {EFFECT_CATEGORY_INFO, isEffectCategory} from '../../common/assembler/EffectCategory';
import {fitVotes} from '../assembler/AssemblerVoteFit';

function read(path: string): Array<AssemblerVote> {
  const file = JSON.parse(fs.readFileSync(path, 'utf8')) as AssemblerVoteFile | Array<AssemblerVote>;
  const votes = Array.isArray(file) ? file : file.votes;
  return votes.filter((v) => isVerdict(v.verdict) && v.assembled?.breakdown !== undefined);
}

function label(group: string): string {
  if (isEffectCategory(group)) {
    return EFFECT_CATEGORY_INFO[group].label;
  }
  return group === 'tags' ? 'Tags' : group === 'payment' ? 'Steel/titanium payment' : 'Requirements';
}

function fmt(n: number, digits = 1): string {
  return n.toFixed(digits);
}

function signed(n: number): string {
  return `${n >= 0 ? '+' : ''}${fmt(n)}`;
}

function report(paths: Array<string>): string {
  // A vote that's in two files (downloaded twice without clearing) counts once.
  const byCard = new Map<string, AssemblerVote>();
  for (const v of paths.flatMap(read)) {
    byCard.set(`${v.card}|${v.at}`, v);
  }
  const votes = [...byCard.values()];
  const fit = fitVotes(votes);
  const lines: Array<string> = [];
  lines.push('# Assembler vote fit', '');
  lines.push(`${fit.votes} votes from ${paths.length} file(s). Generated by \`src/server/tools/assembler_votes.ts\`.`, '');
  lines.push(`Average distance between a card's price and what the votes say it's worth: ${fmt(fit.errorBefore)} M€ now, ${fmt(fit.errorAfter)} M€ with the factors below.`, '');
  lines.push(`Every card: ${fit.offset >= 0 ? '+' : ''}${fmt(fit.offset)} M€ (positive: cards feel too cheap overall).`, '');
  lines.push('Factor: scale the values of that kind of effect by this much. 1.00 = priced right. Few votes = the factor stays near 1 by design.', '');
  lines.push('| Kind of effect | Votes | Average verdict | M€ on a card | Factor | Change on a card |', '|---|---:|---:|---:|---:|---:|');
  for (const g of fit.groups) {
    const mark = Math.abs(g.factor - 1) >= 0.1 && g.votes >= 10 ? '**' : '';
    lines.push(`| ${label(g.group)} | ${g.votes} | ${g.lean >= 0 ? '+' : ''}${fmt(g.lean, 2)} | ${fmt(g.value)} | ${mark}${fmt(g.factor, 2)}${mark} | ${signed((g.factor - 1) * g.value)} |`);
  }
  lines.push('', 'Average verdict: +2 way too cheap, 0 about right, −2 way too expensive.');
  return lines.join('\n') + '\n';
}

function main() {
  const args = process.argv.slice(2);
  const m = args.indexOf('--markdown');
  const out = m >= 0 ? args[m + 1] : undefined;
  const files = args.filter((a, i) => a !== '--markdown' && (m < 0 || i !== m + 1));
  if (files.length === 0) {
    console.error('Usage: npx tsx src/server/tools/assembler_votes.ts votes.json [more.json ...] [--markdown out.md]');
    process.exit(1);
  }
  const text = report(files);
  if (out !== undefined) {
    fs.writeFileSync(out, text);
    console.log(`Wrote ${out}`);
  }
  console.log(text);
}

if (require.main === module) {
  main();
}
